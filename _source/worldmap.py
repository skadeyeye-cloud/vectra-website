def inside(x, y, poly):
    c = False
    for i in range(len(poly)):
        x1, y1 = poly[i]; x2, y2 = poly[i-1]
        if (y1 > y) != (y2 > y) and x < (x2-x1)*(y-y1)/(y2-y1) + x1:
            c = not c
    return c

def svg():
    polys = [[proj(*p) for p in poly] for poly in LAND]
    water = [[proj(*p) for p in poly] for poly in WATER]
    step, dots = 8, []
    y = step/2
    while y < H:
        x = step/2
        while x < W:
            if any(inside(x, y, p) for p in polys) and not any(inside(x, y, p) for p in water):
                dots.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="2"/>')
            x += step
        y += step
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" fill="#9AA6B8">'
            + ''.join(dots) + '</svg>')

